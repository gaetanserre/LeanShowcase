  /* The message of a step of a comparator report: its text, or the end of its process output. */
  function stepMessage(step) {
    const o = step.output || {};
    if (o.str && o.str.string) return o.str.string.trim();
    if (o.proc) {
      const t = ((o.proc.stderr || "") + "\n" + (o.proc.stdout || "")).trim();
      return t.length > 800 ? "…" + t.slice(-800) : t;
    }
    return "";
  }

  /* Why a report rejects the formalization, in comparator's own words: the message of the step
     that failed when it is a single line, otherwise the names and the judgements of the failing
     steps and checkers, as the report writes them. */
  function rejectionReason() {
    const steps = CMP.failedSteps || [];
    const line = steps.find((st) => st.message && !st.message.includes("\n") && st.message.length <= 140);
    if (line) return line.message;
    return steps.map((st) => `${st.key}: ${st.judgement}`)
      .concat((CMP.failed || []).map((k) => `${k}: ${CMP.kernelJudgements[k]}`)).join(" · ") || "failure";
  }

  function comparatorState() {
    const c = D.comparator || {};
    const rep = c.report;
    if (rep && rep.report) {
      const order = Object.keys(CHECKERS);
      const rank = (k) => { const i = order.indexOf(k); return i < 0 ? order.length : i; };
      const kernels = Object.keys(rep.report.kernel_reports || {}).sort((a, b) => rank(a) - rank(b));
      const kjudge = (k) => (rep.report.kernel_reports[k] || {}).judgement;
      const failed = kernels.filter((k) => !["success", "skipped"].includes(kjudge(k)));
      const skipped = kernels.filter((k) => kjudge(k) === "skipped");
      const steps = Object.keys(rep.report).filter((k) => k !== "kernel_reports" && rep.report[k] && rep.report[k].judgement);
      const failedSteps = steps.filter((k) => rep.report[k].judgement !== "success")
        .map((k) => ({ key: k, judgement: rep.report[k].judgement, message: stepMessage(rep.report[k]) }));
      let date = null;
      if (c.reportTime) {
        try { date = new Date(c.reportTime * 1000).toLocaleDateString("en-GB", { year: "numeric", month: "long", day: "numeric" }); }
        catch (e) { date = null; }
      }
      const kernelJudgements = {};
      kernels.forEach((k) => { kernelJudgements[k] = kjudge(k); });
      return { state: rep.judgement === "accepted" ? "verified" : "rejected", kernels, failed, skipped,
        kernelJudgements, failedSteps, sandboxed: rep.sandboxed !== false, date };
    }
    return { state: c.config ? "declared" : "none", kernels: c.checkers || [] };
  }
  const CMP = comparatorState();


  let headingCounter = 0;
  function markdown(text, opts) {
    opts = opts || {};
    const lines = text.replace(/\r/g, "").split("\n");
    const out = [];
    let i = 0;
    const isBlank = (l) => /^\s*$/.test(l);
    const listRe = /^(\s*)([*+-]|\d+[.)])\s+(.*)$/;
    while (i < lines.length) {
      const line = lines[i];
      if (isBlank(line)) { i++; continue; }
      let m;
      if (/^\s*\$\$/.test(line)) {
        // a displayed formula on its own lines: $$ ... $$
        const buf = [line];
        if (!/\$\$\s*$/.test(line.trim().slice(2))) {
          i++;
          while (i < lines.length && !/\$\$\s*$/.test(lines[i])) buf.push(lines[i++]);
          if (i < lines.length) buf.push(lines[i]);
        }
        i++;
        out.push(`<p>${inline(buf.join("\n"))}</p>`);
        continue;
      }
      if ((m = /^\s*```(\w*)/.exec(line))) {
        const lang = m[1];
        const buf = [];
        i++;
        while (i < lines.length && !/^\s*```/.test(lines[i])) buf.push(lines[i++]);
        i++;
        if (lang === "figure") { out.push(figureHtml(buf.join("\n"))); continue; }
        out.push(`<pre class="code"><code>${lang === "lean" || lang === "" ? highlight(buf.join("\n"), null) : esc(buf.join("\n"))}</code></pre>`);
        continue;
      }
      if ((m = /^(#{1,6})\s+(.*)$/.exec(line))) {
        const level = Math.min(6, m[1].length + (opts.shift || 0));
        const id = "h" + (headingCounter++);
        if (opts.headings) opts.headings.push({ level: m[1].length, text: m[2], id });
        out.push(`<h${level} id="${id}">${inline(m[2])}</h${level}>`);
        i++;
        continue;
      }
      if (/^\s*\|/.test(line) && i + 1 < lines.length && /^\s*\|?\s*:?-{2,}/.test(lines[i + 1])) {
        const row = (l) => l.trim().replace(/^\||\|$/g, "").split("|").map((c) => c.trim());
        const head = row(line);
        i += 2;
        const body = [];
        while (i < lines.length && /^\s*\|/.test(lines[i])) body.push(row(lines[i++]));
        out.push(`<div class="table-wrap"><table><thead><tr>${head.map((c) => `<th>${inline(c)}</th>`).join("")}</tr></thead><tbody>${body.map((r) => `<tr>${r.map((c) => `<td>${inline(c)}</td>`).join("")}</tr>`).join("")}</tbody></table></div>`);
        continue;
      }
      if ((m = listRe.exec(line))) {
        const indent = m[1].length;
        const ordered = /\d/.test(m[2]);
        const items = [];
        while (i < lines.length) {
          const l = lines[i];
          const mm = listRe.exec(l);
          if (mm && mm[1].length === indent) {
            items.push([mm[3]]);
            i++;
          } else if (!isBlank(l) && (l.match(/^\s*/)[0].length > indent)) {
            items[items.length - 1].push(l.slice(Math.min(l.match(/^\s*/)[0].length, indent + 2)));
            i++;
          } else if (isBlank(l) && i + 1 < lines.length && listRe.test(lines[i + 1]) &&
              listRe.exec(lines[i + 1])[1].length === indent) {
            i++;
          } else break;
        }
        const tag = ordered ? "ol" : "ul";
        out.push(`<${tag}>${items.map((it) => {
          const first = it[0];
          const rest = it.slice(1);
          const nested = rest.length && rest.some((r) => listRe.test(r));
          if (nested) {
            const k = rest.findIndex((r) => listRe.test(r));
            return `<li>${inline([first].concat(rest.slice(0, k)).join(" "))}${markdown(rest.slice(k).join("\n"))}</li>`;
          }
          return `<li>${inline(it.join(" "))}</li>`;
        }).join("")}</${tag}>`);
        continue;
      }
      if (/^\s*>/.test(line)) {
        const buf = [];
        while (i < lines.length && /^\s*>/.test(lines[i])) buf.push(lines[i++].replace(/^\s*>\s?/, ""));
        out.push(`<blockquote>${markdown(buf.join("\n"))}</blockquote>`);
        continue;
      }
      const buf = [];
      while (i < lines.length && !isBlank(lines[i]) && !/^(#{1,6})\s/.test(lines[i]) &&
          !/^\s*```/.test(lines[i]) && !(buf.length && listRe.test(lines[i]) && !/^\s*\d/.test(lines[i]))) {
        buf.push(lines[i++].trim());
      }
      out.push(`<p>${inline(buf.join(" "))}</p>`);
    }
    return out.join("\n");
  }


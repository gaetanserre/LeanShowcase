  /* Unicode mathematics with `_x`, `_{...}`, `^x`, `^{...}` as sub- and superscripts. */
  function mathText(s) {
    let out = "";
    let i = 0;
    const chars = Array.from(s);
    while (i < chars.length) {
      const c = chars[i];
      if ((c === "_" || c === "^") && i + 1 < chars.length && chars[i + 1] !== " " && i > 0) {
        const tag = c === "_" ? "sub" : "sup";
        if (chars[i + 1] === "{") {
          let depth = 1, j = i + 2;
          while (j < chars.length && depth > 0) {
            if (chars[j] === "{") depth++;
            else if (chars[j] === "}") depth--;
            j++;
          }
          out += `<${tag}>${mathText(chars.slice(i + 2, j - 1).join(""))}</${tag}>`;
          i = j;
        } else {
          let j = i + 1;
          while (j < chars.length && /[\p{L}\p{N}*′']/u.test(chars[j]) && j - i <= 1) j++;
          if (j === i + 1) j++;
          out += `<${tag}>${esc(chars.slice(i + 1, j).join(""))}</${tag}>`;
          i = j;
        }
        continue;
      }
      out += esc(c);
      i++;
    }
    return out;
  }

  /* Markdown inline: code spans, TeX (`$...$` and `$$...$$`, as in docgen), then the rest. */
  function inline(text) {
    // Code spans and TeX are set aside first (as placeholders), so that bold, italic and links can
    // contain them.
    const held = [];
    const hold = (html) => { held.push(html); return `\u0000${held.length - 1}\u0000`; };
    const rest = text.split(/(`+[^`]*?`+)/g).map((p, i) => {
      if (i % 2 === 1) return hold(codeSpan(p.replace(/^`+|`+$/g, "")));
      const parts = p.split(/(\$\$[\s\S]+?\$\$|\$[^$\n]+?\$)/g);
      for (let j = 1; j < parts.length; j += 2) {
        const q = parts[j];
        if (q.startsWith("$$")) {
          parts[j] = hold(`<span class="math display">\\[${esc(q.slice(2, -2))}\\]</span>`);
          continue;
        }
        // An inline formula stays on one line with the characters glued to it, such as a comma
        // or "-almost". Otherwise, the browser may break the line between them, as a rendered
        // formula is a box.
        const lead = parts[j - 1].match(/[^\s$`*_\[\]>]*$/)[0];
        const tail = j + 1 < parts.length ? parts[j + 1].match(/^[^\s$`*_\[\]<]*/)[0] : "";
        parts[j - 1] = parts[j - 1].slice(0, parts[j - 1].length - lead.length);
        if (tail) parts[j + 1] = parts[j + 1].slice(tail.length);
        const math = `<span class="math">\\(${esc(q.slice(1, -1))}\\)</span>`;
        parts[j] = hold(lead || tail ? `<span class="nobr">${esc(lead)}${math}${esc(tail)}</span>` : math);
      }
      return parts.join("");
    }).join("");
    return inlineText(rest).replace(/\u0000(\d+)\u0000/g, (m, k) => held[Number(k)]);
  }

  function inlineText(p) {
      let s = esc(p);
      // images, `![alt](path)` or `![alt](path "title")` (the quotes are escaped here)
      s = s.replace(/!\[([^\]]*)\]\(([^)\s]+)(?:\s+&quot;([^)]*?)&quot;)?\)/g, (a, alt, u, title) =>
        `<img class="md-img" src="${u}" alt="${alt}"${title ? ` title="${title}"` : ""}${sizeAttrs(u)} loading="lazy" decoding="async">`);
      // links. `[Lemma 2](#Name)` goes to the result or the definition `Name` of the page, so that
      // the mathematical texts can refer to them without naming Lean declarations.
      s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (a, t, u) => {
        if (!u.startsWith("#")) return `<a href="${u}" target="_blank" rel="noopener">${t}</a>`;
        const name = u.slice(1).replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/&amp;/g, "&");
        if (name in resultId) return `<a href="#results" data-goto="${resultId[name]}">${t}</a>`;
        if (name in trustId) return `<a href="#definitions" data-goto="${trustId[name]}">${t}</a>`;
        return `<a href="${u}">${t}</a>`;
      });
      s = s.replace(/\[([^\]]+)\]\[([^\]]+)\]/g, (a, t, k) => bib[k] ? cite(k, t) : a);
      s = s.replace(/\[([A-Za-z][\w:-]*\d{2,4}[\w-]*)\]/g, (a, k) => bib[k] ? cite(k) : a);
      s = s.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
      s = s.replace(/(^|[^*\w])\*([^*\s][^*]*?)\*(?!\w)/g, "$1<em>$2</em>");
      s = s.replace(/(https?:\/\/[^\s<]+[^\s<.,;:)])/g, (u, x, off, str) =>
        /href="$/.test(str.slice(0, off)) || /">$/.test(str.slice(0, off)) ? u :
          `<a href="${u}" target="_blank" rel="noopener">${u}</a>`);
      return s;
  }


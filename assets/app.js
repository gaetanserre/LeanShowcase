  /* A map from the ways a declaration may write a constant to that constant. */
  function suffixMap(uses) {
    const map = new Map();
    for (const u of uses || []) {
      const parts = u.split(".");
      for (let k = 1; k <= parts.length; k++) {
        const s = parts.slice(parts.length - k).join(".");
        if (map.has(s) && map.get(s) !== u) map.set(s, null);
        else map.set(s, u);
      }
    }
    return map;
  }


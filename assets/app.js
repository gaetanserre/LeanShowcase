  /* A map from the ways a declaration may write a constant to that constant. */
  function suffixMap(uses) {
    const map = new Map();
    for (const u of uses || []) {
      const parts = u.split(".");
      for (let k = 1; k <= parts.length; k++) {
        const s = parts.slice(parts.length - k).join(".");
        if (map.has(s) && map.get(s) !== u) map.set(s, null);
        else map.set(s, u);
      }
    }
    return map;
  }

  /* Lean source as HTML: keywords and tactics, brackets, the declared name, strings, numbers and
     comments, as in the lexer of CodeLatex. Identifiers link to their definition, unless `noLinks`. */
  function highlight(src, uses, noLinks) {
    const map = suffixMap(uses);
    let out = "";
    let i = 0;
    const n = src.length;
    const tokRe = new RegExp(ID_RE.source, "uy");
    let expectName = false; // after `theorem`, `def`, ...: the next identifier is the declared name
    while (i < n) {
      const c = src[i];
      const two = src.substr(i, 2);
      if (two === "--") {
        let j = src.indexOf("\n", i);
        if (j < 0) j = n;
        out += `<span class="com">${esc(src.slice(i, j))}</span>`;
        i = j;
        continue;
      }
      if (two === "/-") {
        let depth = 0, j = i;
        while (j < n) {
          if (src.substr(j, 2) === "/-") { depth++; j += 2; }
          else if (src.substr(j, 2) === "-/") { depth--; j += 2; if (depth === 0) break; }
          else j++;
        }
        out += `<span class="com">${esc(src.slice(i, j))}</span>`;
        i = j;
        continue;
      }
      if (c === '"') {
        let j = i + 1, body = "";
        while (j < n && src[j] !== '"') {
          if (src[j] === "\\" && j + 1 < n) { body += `<span class="esc">${esc(src.substr(j, 2))}</span>`; j += 2; continue; }
          body += esc(src[j]);
          j++;
        }
        out += `<span class="str">"${body}${j < n ? '"' : ""}</span>`;
        i = j + 1;
        expectName = false;
        continue;
      }
      if (c === "@" && src[i + 1] === "[") {
        const j = src.indexOf("]", i);
        if (j > 0) {
          out += `<span class="br">@[</span><span class="kw">${esc(src.slice(i + 2, j))}</span><span class="br">]</span>`;
          i = j + 1;
          continue;
        }
      }
      if (c === "#") {
        tokRe.lastIndex = i + 1;
        const m = tokRe.exec(src);
        if (m && COMMANDS.has(m[0])) {
          out += `<span class="kw">#${esc(m[0])}</span>`;
          i += 1 + m[0].length;
          continue;
        }
      }
      if (c === "«") {
        const j = src.indexOf("»", i);
        if (j > 0) {
          const id = src.slice(i, j + 1);
          out += expectName ? `<span class="fn">${esc(id)}</span>` : esc(id);
          expectName = false;
          i = j + 1;
          continue;
        }
      }
      if (BRACKETS.includes(c)) {
        out += `<span class="br">${esc(c)}</span>`;
        expectName = false;
        i++;
        continue;
      }
      if (/[0-9]/.test(c) && !/[\w.]/.test(src[i - 1] || "")) {
        let j = i;
        while (j < n && /[0-9.]/.test(src[j])) j++;
        if (src[j - 1] === ".") j--;
        out += `<span class="num">${esc(src.slice(i, j))}</span>`;
        expectName = false;
        i = j;
        continue;
      }
      tokRe.lastIndex = i;
      const m = tokRe.exec(src);
      if (m && m[0].length) {
        const id = m[0];
        const dotted = (src[i - 1] || "") === ".";
        let next = false;
        if (!dotted && id === "sorry") out += `<span class="sorry">sorry</span>`;
        else if (!dotted && KW_PCT.has(id) && src[i + id.length] === "%") {
          out += `<span class="kw">${esc(id)}%</span>`;
          i++;
        } else if (!dotted && KW.has(id)) {
          out += `<span class="kw">${esc(id)}</span>`;
          next = DEF_CMDS.has(id);
        } else if (expectName) out += `<span class="fn">${esc(id)}</span>`;
        else if (!noLinks && !dotted && map.get(id)) out += constLink(map.get(id), id);
        else if (!noLinks && !dotted && refs[id]) out += constLink(refs[id], id);
        else out += esc(id);
        expectName = next;
        i += id.length;
        continue;
      }
      if (!/\s/.test(c)) expectName = false;
      out += esc(c);
      i++;
    }
    return out;
  }

  /* The pretty-printed signature: the declared name, then pieces of text, linked to the constants
     they print. */
  function signature(d) {
    const kw = KEYWORD[d.kind] || "";
    let out = kw ? `<span class="kw">${kw}</span> ` : "";
    (d.signature || []).forEach((p, idx) => {
      let text = typeof p === "string" ? p : p[0];
      if (idx === 0) text = text.replace(/\.\{[^}]*\}/, "");
      if (typeof p === "string") {
        const m0 = idx === 0 ? /^(\S+)([\s\S]*)$/.exec(text) : null;
        out += m0 ? `<span class="fn">${esc(m0[1])}</span>${highlight(m0[2], null, true)}` : highlight(text, null, true);
        return;
      }
      const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(text);
      if (!m[2] || /^[()\[\]{},:⦃⦄⟨⟩]+$/.test(m[2])) { out += highlight(text, null, true); return; }
      out += esc(m[1]) + constLink(p[1], m[2]) + esc(m[3]);
    });
    return out;
  }


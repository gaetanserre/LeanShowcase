  /* Renders the TeX of `el` with MathJax, once it has loaded (see the template). */
  function typeset(el) {
    const mj = window.MathJax;
    if (mj && typeof mj.typesetPromise === "function") {
      mj.typesetPromise([el]).then(() => { layoutMaps(el); spyToc(); }).catch(() => {});
    }
  }

  /* Opens, in the table of contents of the results, the menu of the section being read, and closes
     the others. Also marks the heading or the result being read. Only on wide screens, where the
     table of contents stays on the side: above the text, opening a menu would move the text. */
  let spyQueued = false;
  function spyToc() {
    spyQueued = false;
    const nav = app.querySelector(".toc");
    if (!nav) return;
    const secs = [...nav.querySelectorAll("li.sec")];
    const links = [...nav.querySelectorAll("a[data-goto]")];
    if (getComputedStyle(nav).position !== "sticky") {
      secs.forEach((li) => li.classList.remove("open"));
      links.forEach((a) => a.removeAttribute("aria-current"));
      return;
    }
    // an element is reached once its top passes just below its scroll margin (5rem)
    const line = 6 * parseFloat(getComputedStyle(document.documentElement).fontSize);
    const reached = (id) => {
      const el = document.getElementById(id);
      return !!el && el.getBoundingClientRect().top <= line;
    };
    const open = secs.filter((li) => reached(li.dataset.sec)).pop();
    secs.forEach((li) => li.classList.toggle("open", li === open));
    const here = links.filter((a) => reached(a.dataset.goto)).pop();
    links.forEach((a) => {
      if (a === here) a.setAttribute("aria-current", "location");
      else a.removeAttribute("aria-current");
    });
    // keeps the current entry visible in the table of contents
    if (here && nav.scrollHeight > nav.clientHeight) {
      const n = nav.getBoundingClientRect();
      const r = here.getBoundingClientRect();
      if (r.top < n.top) nav.scrollTop -= n.top - r.top + 8;
      else if (r.bottom > n.bottom) nav.scrollTop += r.bottom - n.bottom + 8;
    }
  }
  const queueSpy = () => {
    if (!spyQueued) { spyQueued = true; requestAnimationFrame(spyToc); }
  };
  window.addEventListener("scroll", queueSpy, { passive: true });
  window.addEventListener("resize", queueSpy);
  let mapsQueued = false;
  window.addEventListener("resize", () => {
    if (!mapsQueued) {
      mapsQueued = true;
      requestAnimationFrame(() => { mapsQueued = false; layoutMaps(app); });
    }
  });
  window.showcaseTypeset = () => typeset(app);


  function splitDoc(doc) {
    if (!doc) return { title: null, rest: "", ref: null };
    const m = /^\s*\*\*(.+?)\*\*\s*([\s\S]*)$/.exec(doc);
    if (!m) return { title: null, rest: doc, ref: null };
    let rest = m[2], ref = null;
    // "**Title** (Theorem 3.1 of [Paper]). Statement..." : the reference goes to the header.
    const r = /^\(((?:[^()]|\([^()]*\))*)\)\s*[.:]\s*/.exec(rest);
    if (r) { ref = r[1]; rest = rest.slice(r[0].length); }
    return { title: m[1].replace(/[.:]$/, ""), rest: rest.replace(/^[.:]\s*/, ""), ref };
  }

  function refHtml(ref, label) {
    if (!ref) return "";
    let r = ref;
    if (label && r.indexOf(label) === 0) r = r.slice(label.length).replace(/^\s*(of|in)\s+/, "");
    return r.trim() ? `<span class="ref">${inline(r.trim())}</span>` : "";
  }

